CREATE TABLE aluno (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    cpf         VARCHAR(11)  NOT NULL UNIQUE,
    email       VARCHAR(150) NOT NULL UNIQUE,
    senha_hash  VARCHAR(100) NOT NULL,
    telefone    VARCHAR(20),
    criado_em   TIMESTAMP    NOT NULL DEFAULT NOW()
);

CREATE TABLE curso (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150)  NOT NULL UNIQUE,
    grau           VARCHAR(30)   NOT NULL,
    descricao      VARCHAR(500),
    duracao_meses  INTEGER       NOT NULL CHECK (duracao_meses > 0),
    valor_total    NUMERIC(10,2) NOT NULL CHECK (valor_total > 0),
    max_parcelas   INTEGER       NOT NULL CHECK (max_parcelas BETWEEN 1 AND 24),
    ativo          BOOLEAN       NOT NULL DEFAULT TRUE
);

-- Turnos em que cada curso é oferecido
CREATE TABLE curso_turno (
    curso_id  BIGINT      NOT NULL REFERENCES curso(id) ON DELETE CASCADE,
    turno     VARCHAR(20) NOT NULL CHECK (turno IN ('MATUTINO', 'VESPERTINO', 'NOTURNO')),
    PRIMARY KEY (curso_id, turno)
);

CREATE TABLE matricula (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id          BIGINT        NOT NULL REFERENCES aluno(id),
    curso_id          BIGINT        NOT NULL REFERENCES curso(id),
    turno             VARCHAR(20)   NOT NULL CHECK (turno IN ('MATUTINO', 'VESPERTINO', 'NOTURNO')),
    valor_total       NUMERIC(10,2) NOT NULL,
    forma_pagamento   VARCHAR(20)   NOT NULL CHECK (forma_pagamento IN ('BOLETO', 'CARTAO', 'PIX')),
    status            VARCHAR(30)   NOT NULL CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'CONFIRMADA', 'CANCELADA')),
    aceite_termos_em  TIMESTAMP     NOT NULL,
    criado_em         TIMESTAMP     NOT NULL DEFAULT NOW(),
    confirmada_em     TIMESTAMP
);

CREATE INDEX idx_matricula_aluno ON matricula(aluno_id);

-- Um aluno só pode ter UMA matrícula confirmada por curso
CREATE UNIQUE INDEX uk_matricula_confirmada_por_curso
    ON matricula(aluno_id, curso_id) WHERE status = 'CONFIRMADA';

CREATE TABLE pagamento (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id      BIGINT        NOT NULL UNIQUE REFERENCES matricula(id),
    metodo            VARCHAR(20)   NOT NULL CHECK (metodo IN ('BOLETO', 'CARTAO', 'PIX')),
    status            VARCHAR(20)   NOT NULL CHECK (status IN ('PENDENTE', 'APROVADO', 'RECUSADO', 'CANCELADO')),
    valor             NUMERIC(10,2) NOT NULL,
    parcelas          INTEGER       NOT NULL DEFAULT 1,
    valor_parcela     NUMERIC(10,2) NOT NULL,
    codigo_transacao  VARCHAR(30),
    -- Boleto
    codigo_barras     VARCHAR(44),
    linha_digitavel   VARCHAR(60),
    vencimento        DATE,
    -- Pix
    pix_copia_cola    VARCHAR(512),
    -- Cartão: NUNCA guardamos o número completo nem o CVC
    cartao_final      VARCHAR(4),
    cartao_bandeira   VARCHAR(20),
    cartao_titular    VARCHAR(120),
    criado_em         TIMESTAMP     NOT NULL DEFAULT NOW(),
    pago_em           TIMESTAMP
);
